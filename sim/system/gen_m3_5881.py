# Writes rtl/sys/m3_5881.sv, the 315-5881's block cipher (study R100), from
# MAME 0.289's src/mame/sega/315-5881_crypt.cpp (BSD-3-Clause, Andreas Naive,
# Olivier Galibert, David Haywood; THIRD_PARTY.md): its S-boxes and key
# schedules are read from that file, and the cipher's structure
# (block_decrypt) is written out as logic. Also a Python model of
# block_decrypt, for vectors:
#
#   gen_m3_5881.py MAME_315-5881_crypt.cpp --out rtl/sys/m3_5881.sv
#   gen_m3_5881.py MAME_315-5881_crypt.cpp --vectors N --key K --out file    (counter subkey data result)
import argparse, random, re, sys


def ints(txt):
    return [int(x) for x in re.findall(r'-?\d+', txt)]


def block(src, name):
    i = src.index(name)
    i = src.index('{', i)
    depth, j = 0, i
    while True:
        if src[j] == '{': depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    return src[i:j + 1]


def load(fn):
    src = open(fn).read()
    src = re.sub(r'//[^\n]*', '', src)
    t = {}
    for fn_ in ('fn1_sboxes', 'fn2_sboxes'):
        v = ints(block(src, 'sega_315_5881_crypt_device::' + fn_ + '[4][4] ='))
        assert len(v) == 16 * 72, (fn_, len(v))
        t[fn_] = [[(v[(r * 4 + m) * 72:(r * 4 + m) * 72 + 64], v[(r * 4 + m) * 72 + 64:(r * 4 + m) * 72 + 70],
                    v[(r * 4 + m) * 72 + 70:(r * 4 + m) * 72 + 72]) for m in range(4)] for r in range(4)]
    for nm, n in (('fn1_game_key_scheduling', 38), ('fn2_game_key_scheduling', 32), ('fn1_sequence_key_scheduling', 20)):
        v = ints(block(src, 'sega_315_5881_crypt_device::' + nm))
        assert len(v) == 2 * n, (nm, len(v))
        t[nm] = [(v[2 * k], v[2 * k + 1]) for k in range(n)]
    for nm in ('fn2_sequence_key_scheduling', 'fn2_middle_result_scheduling'):
        v = ints(block(src, 'sega_315_5881_crypt_device::' + nm + '[16] ='))
        assert len(v) == 16, nm
        t[nm] = v
    return t


def bitswap16(x, order):              # MAME's BITSWAP16: order[0] is the result's bit 15
    r = 0
    for k, b in enumerate(order):
        r |= ((x >> b) & 1) << (15 - k)
    return r


SW_CTR = [5, 12, 14, 13, 9, 3, 6, 4, 8, 1, 15, 11, 0, 7, 10, 2]
SW_IN = [14, 3, 8, 12, 13, 7, 15, 4, 6, 2, 9, 5, 11, 0, 1, 10]
SW_OUT = [15, 7, 6, 14, 13, 12, 5, 4, 3, 2, 11, 10, 9, 1, 0, 8]


def feistel(t, fn, r, inp, sk):
    res = 0
    for m in range(4):
        table, ins, outs = t[fn][r][m]
        aux = 0
        for k in range(6):
            if ins[k] != -1:
                aux |= ((inp >> ins[k]) & 1) << k
        a = table[(aux ^ (sk >> (6 * m))) & 0x3f]
        for k in range(2):
            res |= ((a >> k) & 1) << outs[k]
    return res


def subkeys(t, game_key, seq):
    k1 = k2 = 0
    for b, p in t['fn1_game_key_scheduling']:
        if (game_key >> b) & 1: k1 ^= 1 << p
    for b, p in t['fn2_game_key_scheduling']:
        if (game_key >> b) & 1: k2 ^= 1 << p
    for b, p in t['fn1_sequence_key_scheduling']:
        if (seq >> b) & 1: k1 ^= 1 << p
    for b, p in enumerate(t['fn2_sequence_key_scheduling']):
        if (seq >> b) & 1: k2 ^= 1 << p
    return k1, k2


def block_decrypt(t, game_key, seq, counter, data):
    k1, k2 = subkeys(t, game_key, seq)
    aux = bitswap16(counter, SW_CTR)
    B, A = aux >> 8, aux & 0xff
    A ^= feistel(t, 'fn1_sboxes', 0, B, k1 & 0xffffff)
    B ^= feistel(t, 'fn1_sboxes', 1, A, (k1 >> 24) & 0xffffff)
    A ^= feistel(t, 'fn1_sboxes', 2, B, (k1 >> 48) & 0xffffff)
    B ^= feistel(t, 'fn1_sboxes', 3, A, (k1 >> 72) & 0xffffff)
    mid = (B << 8) | A
    for b, p in enumerate(t['fn2_middle_result_scheduling']):
        if (mid >> b) & 1: k2 ^= 1 << p
    aux = bitswap16(data, SW_IN)
    B, A = aux >> 8, aux & 0xff
    A ^= feistel(t, 'fn2_sboxes', 0, B, k2 & 0xffffff)
    B ^= feistel(t, 'fn2_sboxes', 1, A, (k2 >> 24) & 0xffffff)
    A ^= feistel(t, 'fn2_sboxes', 2, B, (k2 >> 48) & 0xffffff)
    B ^= feistel(t, 'fn2_sboxes', 3, A, (k2 >> 72) & 0xffffff)
    return bitswap16((B << 8) | A, SW_OUT)


def sv(t, mame_path):
    L = []
    w = L.append
    w('// SPDX-License-Identifier: GPL-3.0-or-later')
    w('//')
    w('// Sega Model 3 core for MiSTer FPGA')
    w('// Copyright (C) 2026 alphanu1')
    w('//')
    w('// This program is free software: you can redistribute it and/or modify it')
    w('// under the terms of the GNU General Public License as published by the Free')
    w('// Software Foundation, either version 3 of the License, or (at your option)')
    w('// any later version. See LICENSE for the full text.')
    w('//')
    w('// ---------------------------------------------------------------------------')
    w('//')
    w('// GENERATED by sim/system/gen_m3_5881.py from MAME 0.289')
    w('// src/mame/sega/315-5881_crypt.cpp; do not edit. The S-box tables and key')
    w('// schedules below are MAME\'s (license:BSD-3-Clause, copyright-holders:')
    w('// Andreas Naive, Olivier Galibert, David Haywood; THIRD_PARTY.md).')
    w('//')
    w('// The 315-5881 security chip\'s block cipher (study R100): MAME\'s')
    w('// block_decrypt(game_key, sequence_key, counter, data) as logic. Two Feistel')
    w('// networks of four rounds; the first takes the counter (the word\'s address),')
    w('// its result keys the second, which takes the encrypted word. Four clocks:')
    w('// two rounds a clock, results in registers between. go starts one; dec is')
    w('// valid in the cycle done is high and stays until the next go. The subkeys')
    w('// from the game key and the sequence key are registered when they change')
    w('// (k_ld: both are static over a stream).')
    w('')
    w('module m3_5881 (')
    w('  input  logic        clk,')
    w('  input  logic        k_ld,           // load the key schedule (game_key, seq_key settled)')
    w('  input  logic [29:0] game_key,')
    w('  input  logic [15:0] seq_key,')
    w('  input  logic        go,')
    w('  input  logic [15:0] counter,')
    w('  input  logic [15:0] data,')
    w('  output logic        done,')
    w('  output logic [15:0] dec')
    w(');')
    w('')
    # feistel functions
    for fn in ('fn1_sboxes', 'fn2_sboxes'):
        for r in range(4):
            nm = 'f%s_r%d' % (fn[2], r)
            w('  function automatic logic [7:0] %s(input logic [7:0] x, input logic [23:0] sk);' % nm)
            w('    logic [5:0] a;')
            w('    logic [1:0] v;')
            w('    %s = 8\'d0;' % nm)
            for m in range(4):
                table, ins, outs = t[fn][r][m]
                bits = ', '.join(("1'b0" if ins[k] == -1 else 'x[%d]' % ins[k]) for k in reversed(range(6)))
                w('    a = {%s} ^ sk[%d:%d];' % (bits, 6 * m + 5, 6 * m))
                w('    case (a)')
                for i in range(64):
                    w("      6'd%d: v = 2'd%d;" % (i, table[i] & 3))
                w('      default: v = 2\'d0;')
                w('    endcase')
                w('    %s[%d] = %s[%d] | v[0];' % (nm, outs[0], nm, outs[0]))
                w('    %s[%d] = %s[%d] | v[1];' % (nm, outs[1], nm, outs[1]))
            w('  endfunction')
            w('')

    def xor_terms(sched_pairs, src):
        terms = {}
        for b, p in sched_pairs:
            terms.setdefault(p, []).append('%s[%d]' % (src, b))
        return terms
    w('  // key schedules (96 subkey bits a network: rounds 0-3 of 24 bits each)')
    w('  logic [95:0] k1, k2b;')
    w('  always_ff @(posedge clk) if (k_ld) begin')
    t1 = xor_terms(t['fn1_game_key_scheduling'], 'game_key')
    for p, ts in xor_terms(t['fn1_sequence_key_scheduling'], 'seq_key').items():
        t1.setdefault(p, []).extend(ts)
    t2 = xor_terms(t['fn2_game_key_scheduling'], 'game_key')
    for p, ts in xor_terms(list(enumerate(t['fn2_sequence_key_scheduling'])), 'seq_key').items():
        t2.setdefault(p, []).extend(ts)
    for p in range(96):
        w('    k1[%d] <= %s;' % (p, ' ^ '.join(t1[p]) if p in t1 else "1'b0"))
    for p in range(96):
        w('    k2b[%d] <= %s;' % (p, ' ^ '.join(t2[p]) if p in t2 else "1'b0"))
    w('  end')
    w('')
    w('  function automatic logic [15:0] swap16(input logic [15:0] x, input int sel);')
    w('    case (sel)')
    for k, order in enumerate((SW_CTR, SW_IN, SW_OUT)):
        w('      %d: swap16 = {%s};' % (k, ', '.join('x[%d]' % b for b in order)))
    w('      default: swap16 = x;')
    w('    endcase')
    w('  endfunction')
    w('')
    w('  // the middle result\'s part of the second network\'s key')
    w('  function automatic logic [95:0] kmid(input logic [15:0] m);')
    w('    kmid = 96\'d0;')
    for b, p in enumerate(t['fn2_middle_result_scheduling']):
        w('    kmid[%d] = kmid[%d] ^ m[%d];' % (p, p, b))
    w('  endfunction')
    w('')
    w('  logic [3:0]  st;')
    w('  logic [7:0]  a, b;')
    w('  logic [15:0] d_q;')
    w('  logic [95:0] k2;')
    w('  always_ff @(posedge clk) begin')
    w('    st <= {st[2:0], go};')
    w('    if (go) begin')
    w('      logic [15:0] s;')
    w('      logic [7:0]  aa, bb;')
    w('      s = swap16(counter, 0);')
    w('      bb = s[15:8];')
    w('      aa = s[7:0] ^ f1_r0(bb, k1[23:0]);')
    w('      bb = bb ^ f1_r1(aa, k1[47:24]);')
    w('      a <= aa; b <= bb; d_q <= data;')
    w('    end')
    w('    if (st[0]) begin')
    w('      logic [7:0] aa, bb;')
    w('      aa = a ^ f1_r2(b, k1[71:48]);')
    w('      bb = b ^ f1_r3(aa, k1[95:72]);')
    w('      k2 <= k2b ^ kmid({bb, aa});')
    w('      begin')
    w('        logic [15:0] s;')
    w('        s = swap16(d_q, 1);')
    w('        b <= s[15:8]; a <= s[7:0];')
    w('      end')
    w('    end')
    w('    if (st[1]) begin')
    w('      logic [7:0] aa, bb;')
    w('      aa = a ^ f2_r0(b, k2[23:0]);')
    w('      bb = b ^ f2_r1(aa, k2[47:24]);')
    w('      a <= aa; b <= bb;')
    w('    end')
    w('    if (st[2]) begin')
    w('      logic [7:0] aa, bb;')
    w('      aa = a ^ f2_r2(b, k2[71:48]);')
    w('      bb = b ^ f2_r3(aa, k2[95:72]);')
    w('      dec <= swap16({bb, aa}, 2);')
    w('    end')
    w('  end')
    w('  assign done = st[3];')
    w('')
    w('endmodule')
    return '\n'.join(L) + '\n'


def main():
    p = argparse.ArgumentParser()
    p.add_argument('mame')
    p.add_argument('--out', required=True)
    p.add_argument('--vectors', type=int, default=0)
    p.add_argument('--key', type=lambda x: int(x, 16), default=0x29250e16)
    p.add_argument('--seed', type=int, default=1)
    a = p.parse_args()
    t = load(a.mame)
    if a.vectors:
        rng = random.Random(a.seed)
        with open(a.out, 'w') as f:
            for _ in range(a.vectors):
                seq, ctr, d = rng.getrandbits(16), rng.getrandbits(16), rng.getrandbits(16)
                f.write('%04x %04x %04x %04x\n' % (ctr, seq, d, block_decrypt(t, a.key, seq, ctr, d)))
        print('wrote', a.vectors, 'vectors to', a.out)
    else:
        open(a.out, 'w').write(sv(t, a.mame))
        print('wrote', a.out)


if __name__ == '__main__':
    main()
